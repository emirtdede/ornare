    public static IReadOnlyList<EmojiEntry> All => LazyEntries.Value;

    public static IReadOnlyList<EmojiEntry> Search(string query, string? category = null)
    {
        var entries = LazyEntries.Value.AsEnumerable();

        if (!string.IsNullOrWhiteSpace(category) && !string.Equals(category, "All", StringComparison.OrdinalIgnoreCase))
        {
            entries = entries.Where(e => string.Equals(e.Category, category, StringComparison.OrdinalIgnoreCase));
        }

        if (string.IsNullOrWhiteSpace(query))
        {
            return entries.ToList();
        }

        string normalized = query.Trim().ToLowerInvariant();
        string trimmed = query.Trim();
        return entries
            .Where(e => e.Name.Contains(normalized, StringComparison.OrdinalIgnoreCase) ||
                        e.Keywords.Any(k => k.Contains(normalized, StringComparison.OrdinalIgnoreCase)) ||
                        e.Grapheme == trimmed ||
                        trimmed.StartsWith(e.Grapheme, StringComparison.Ordinal) ||
                        e.Grapheme.StartsWith(trimmed, StringComparison.Ordinal))
            .ToList();
    }

