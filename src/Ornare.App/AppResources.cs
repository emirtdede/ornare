    private static string _currentLocale = "en-US";

    public static string CurrentLocale
    {
        get => _currentLocale;
        set => _currentLocale = NormalizeLocale(value);
    }

    public static string NormalizeLocale(string? lang)
    {
        if (string.IsNullOrWhiteSpace(lang) || string.Equals(lang, "System", StringComparison.OrdinalIgnoreCase))
        {
            string sys = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();
            return sys switch
            {
                "tr" => "tr-TR",
                "de" => "de-DE",
                "fr" => "fr-FR",
                "es" => "es-ES",
                "pt" => "pt-BR",
                _ => "en-US"
            };
        }

        string clean = lang.Trim();
        if (clean.StartsWith("tr", StringComparison.OrdinalIgnoreCase)) return "tr-TR";
        if (clean.StartsWith("de", StringComparison.OrdinalIgnoreCase)) return "de-DE";
        if (clean.StartsWith("fr", StringComparison.OrdinalIgnoreCase)) return "fr-FR";
        if (clean.StartsWith("es", StringComparison.OrdinalIgnoreCase)) return "es-ES";
        if (clean.StartsWith("pt", StringComparison.OrdinalIgnoreCase)) return "pt-BR";
        return "en-US";
    }

    public static string GetString(string key, string? lang = null)
    {
        string locale = lang != null ? NormalizeLocale(lang) : _currentLocale;

        if (_resources.TryGetValue(locale, out var dict) && dict.TryGetValue(key, out var val))
        {
            return val;
        }

        if (_resources["en-US"].TryGetValue(key, out var fallback))
        {
            return fallback;
        }

        return key;
    }

    public static string Format(string key, string? lang, params object[] args)
    {
        string pattern = GetString(key, lang);
        try
        {
            return string.Format(CultureInfo.InvariantCulture, pattern, args);
        }
        catch
        {
            return pattern;
        }
    }

